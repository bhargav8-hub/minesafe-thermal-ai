export function generateHistoricalData(hours: number = 24): ChartDataPoint[] {
  const data: ChartDataPoint[] = [];
  const now = Date.now();
  const points = hours * 12; // every 5 minutes

  for (let i = points; i >= 0; i--) {
    const time = new Date(now - i * 5 * 60 * 1000);
    const hour = time.getHours();
    const baseTemp = 27 + Math.sin((hour / 24) * Math.PI * 2) * 2;
    data.push({
      time: time.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' }),
      temperature: +(baseTemp + (Math.random() - 0.5) * 1.5).toFixed(1),
      humidity: +(68 + Math.sin((hour / 24) * Math.PI) * 10 + (Math.random() - 0.5) * 3).toFixed(1),
      co2: +(850 + Math.sin((hour / 24) * Math.PI) * 200 + (Math.random() - 0.5) * 100).toFixed(0),
      airflow: +(2.8 + (Math.random() - 0.5) * 0.5).toFixed(2),
    });
  }
  return data;
}
